// Generates src/base/unicode_tables.inc: the Unicode properties soju-rs gets
// from Rust's char and str methods, from the toolchain soju-rs is built with,
// so src/base/utf8.c answers exactly like it (PLAN.md section 1).
//
//   tools/gen-unicode-tables.sh
//
// Tables are sorted ranges or sorted mappings, looked up by binary search.

use std::fmt::Write;

fn ranges(f: impl Fn(char) -> bool) -> Vec<(u32, u32)> {
    let mut out: Vec<(u32, u32)> = Vec::new();
    for cp in 0..=0x10FFFFu32 {
        let Some(c) = char::from_u32(cp) else { continue };
        if !f(c) {
            continue;
        }
        match out.last_mut() {
            // Surrogates aren't chars: ranges may span them
            Some(last) if last.1 + 1 == cp || (last.1 == 0xD7FF && cp == 0xE000) => last.1 = cp,
            _ => out.push((cp, cp)),
        }
    }
    out
}

fn emit_ranges(out: &mut String, name: &str, r: &[(u32, u32)]) {
    writeln!(out, "static const struct utf8_range {name}[] = {{").unwrap();
    for (lo, hi) in r {
        writeln!(out, "\t{{0x{lo:X}, 0x{hi:X}}},").unwrap();
    }
    writeln!(out, "}};").unwrap();
}

// Characters whose mapping isn't the character itself, with up to three
// output characters
fn emit_mapping(out: &mut String, name: &str, f: impl Fn(char) -> Vec<char>) {
    writeln!(out, "static const struct utf8_case {name}[] = {{").unwrap();
    for cp in 0..=0x10FFFFu32 {
        let Some(c) = char::from_u32(cp) else { continue };
        let m = f(c);
        if m.len() == 1 && m[0] == c {
            continue;
        }
        assert!(m.len() <= 3);
        let vals: Vec<String> = m.iter().map(|c| format!("0x{:X}", *c as u32)).collect();
        writeln!(out, "\t{{0x{cp:X}, {}, {{{}}}}},", m.len(), vals.join(", ")).unwrap();
    }
    writeln!(out, "}};").unwrap();
}

fn main() {
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by tools/gen-unicode-tables.rs with {}. Do not edit.",
        env!("SOJU_RUSTC_VERSION")
    )
    .unwrap();
    emit_ranges(&mut out, "alphabetic_ranges", &ranges(char::is_alphabetic));
    emit_ranges(&mut out, "numeric_ranges", &ranges(char::is_numeric));
    emit_ranges(&mut out, "lowercase_ranges", &ranges(char::is_lowercase));
    emit_ranges(&mut out, "uppercase_ranges", &ranges(char::is_uppercase));
    // Characters that `{:?}` on a str prints as \u{...}: not printable, or
    // grapheme extenders
    emit_ranges(
        &mut out,
        "debug_escape_ranges",
        &ranges(|c| {
            let s = format!("{:?}", c.to_string());
            s.starts_with("\"\\u{")
        }),
    );
    // For the final sigma rule of str::to_lowercase (Cased and
    // Case_Ignorable aren't public in std: probed through to_lowercase)
    emit_ranges(&mut out, "case_ignorable_ranges", &ranges(is_case_ignorable));
    emit_ranges(&mut out, "cased_ranges", &ranges(|c| !is_case_ignorable(c) && final_sigma(&[c])));
    emit_mapping(&mut out, "upper_map", |c| c.to_uppercase().collect());
    emit_mapping(&mut out, "lower_map", |c| c.to_lowercase().collect());
    print!("{out}");
}

// Whether "<chars>Σ" lowercases the sigma to the final form 'ς'. Rust
// does when the sigma is preceded by a cased character, skipping
// case-ignorable ones, and isn't followed by one.
fn final_sigma(before: &[char]) -> bool {
    let s: String = before.iter().chain(['Σ'].iter()).collect();
    s.to_lowercase().ends_with('ς')
}

// A case-ignorable c is skipped: "AcΣ" ends with a final sigma (A is
// cased), "cΣ" doesn't (nothing before). Any other c decides both alike.
fn is_case_ignorable(c: char) -> bool {
    final_sigma(&['A', c]) && !final_sigma(&[c])
}
