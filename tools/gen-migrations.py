#!/usr/bin/env python3
"""Generates src/db/migrations.inc from soju-rs's
src/database/sqlite_migrations.rs (git show <rev>:...), so the C port runs
exactly the same SQL."""
import re
import subprocess
import sys

rev = sys.argv[1] if len(sys.argv) > 1 else "c350574"
src = subprocess.run(["git", "show", f"{rev}:src/database/sqlite_migrations.rs"],
                     capture_output=True, text=True, check=True).stdout
body = src[src.index("&[") + 2:src.rindex("];")]
items = []
pos = 0
pattern = re.compile(r'r#"(.*?)"#|include_str!\("([^"]+)"\)|//[^\n]*', re.S)
for m in pattern.finditer(body):
    if m.group(0).startswith("//"):
        continue
    if m.group(1) is not None:
        items.append(m.group(1))
    else:
        path = "src/database/" + m.group(2)
        items.append(subprocess.run(["git", "show", f"{rev}:{path}"],
                                    capture_output=True, text=True, check=True).stdout)

def c_string(s):
    out = []
    for line in s.splitlines(keepends=True):
        esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\n", "\\n")
        out.append(f'\t"{esc}"')
    return "\n".join(out) if out else '\t""'

with open("src/db/migrations.inc", "w") as f:
    f.write(f"// Generated by tools/gen-migrations.py from soju-rs {rev}. Do not edit.\n")
    f.write("// clang-format off\n")
    for i, s in enumerate(items):
        f.write(f"\t// #{i}\n{c_string(s)},\n")
    f.write("// clang-format on\n")
print(len(items))
